function Button({
  className,
  variant = "default",
  size = "default",
  render,
  nativeButton,
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      /*
       * Every button that navigates passes a link through `render`, and Base UI
       * warns that it is no longer rendering a native <button>. That is exactly
       * what we want here — a link should be a link — so the flag follows the
       * render prop instead of being switched off for the whole app, which
       * would take the native semantics away from the real submit buttons too.
       */
      nativeButton={nativeButton ?? (render ? false : undefined)}
      render={render}
      {...props}
    />
  )
}

export { Button, buttonVariants }
